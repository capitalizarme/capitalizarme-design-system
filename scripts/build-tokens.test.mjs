import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import {
  KIT_TOKENS,
  CONTRACT_ADDITIONS,
  FOCUS_RING_OVERRIDE,
  parseRootDeclarations,
  buildTokensCss,
  checkTokens,
} from "./build-tokens.mjs";

const SOURCE = readFileSync(
  fileURLToPath(new URL("../colors_and_type.css", import.meta.url)),
  "utf8",
);

const escape = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

test("KIT_TOKENS lists the 56 kit contract names", () => {
  assert.equal(KIT_TOKENS.length, 56);
  assert.equal(new Set(KIT_TOKENS).size, 56);
});

test("parseRootDeclarations ignores comments, keeps complex values, reads only the first top-level :root", () => {
  const fixture =
    ':root { /* a 4.76:1; --x: y */ --a: 1px; ' +
    "--shadow-sm: 0 1px 2px rgba(37, 57, 127, 0.06), 0 1px 1px rgba(37, 57, 127, 0.04); " +
    '--font-display: "Space Grotesk", sans-serif; } ' +
    "@media (min-width: 1px) { :root { --a: 9px; } }";
  assert.deepEqual(parseRootDeclarations(fixture), [
    { name: "--a", value: "1px" },
    {
      name: "--shadow-sm",
      value: "0 1px 2px rgba(37, 57, 127, 0.06), 0 1px 1px rgba(37, 57, 127, 0.04)",
    },
    { name: "--font-display", value: '"Space Grotesk", sans-serif' },
  ]);
});

test("parseRootDeclarations skips a :root nested inside an at-rule before the top-level one", () => {
  const fixture = "@media print { :root { --a: 9px; } } :root { --a: 1px; }";
  assert.deepEqual(parseRootDeclarations(fixture), [{ name: "--a", value: "1px" }]);
});

test("buildTokensCss on the real source declares every kit token", () => {
  const out = buildTokensCss(SOURCE);
  for (const name of KIT_TOKENS) {
    assert.match(out, new RegExp(`^\\s*${escape(name)}:`, "m"), `missing ${name}`);
  }
});

test("buildTokensCss replaces --focus-ring in place, once, with the box-shadow override", () => {
  const out = buildTokensCss(SOURCE);
  assert.equal(out.match(/--focus-ring:/g).length, 1);
  assert.match(out, new RegExp(`^  --focus-ring: ${escape(FOCUS_RING_OVERRIDE)};$`, "m"));
  // in place: before the contract-additions comment, right before --focus-ring-offset
  assert.ok(out.indexOf("--focus-ring:") < out.indexOf("Open Design kit contract additions"));
  assert.ok(out.indexOf("--focus-ring:") < out.indexOf("--focus-ring-offset:"));
});

test("buildTokensCss output is self-contained", () => {
  const out = buildTokensCss(SOURCE);
  assert.ok(!out.includes("@import"));
  assert.equal(out.match(/:root\s*\{/g).length, 1);
  assert.ok(out.startsWith("/* GENERATED by scripts/build-tokens.mjs from colors_and_type.css — do not edit */"));
  assert.ok(out.endsWith("}\n"));
  const declared = new Set([...out.matchAll(/^\s*(--[\w-]+):/gm)].map((m) => m[1]));
  for (const [, ref] of out.matchAll(/var\(\s*(--[\w-]+)/g)) {
    assert.ok(declared.has(ref), `var(${ref}) is not declared`);
  }
  assert.match(out, /^  --color-brand-navy: #25397f;$/m);
});

test("buildTokensCss emits contract additions with exact values, in order, after the marker", () => {
  const out = buildTokensCss(SOURCE);
  const marker = out.indexOf(
    "/* ---- Open Design kit contract additions (DERIVED aliases — see docs/open-design-agent-kit.md) ---- */",
  );
  assert.ok(marker > 0);
  let last = marker;
  for (const [name, value] of Object.entries(CONTRACT_ADDITIONS)) {
    const line = `  ${name}: ${value};`;
    const at = out.indexOf(line);
    assert.ok(at > last, `${line} missing or out of order`);
    last = at;
  }
  assert.equal(CONTRACT_ADDITIONS["--accent-hover"], "color-mix(in oklab, var(--accent), black 8%)");
  assert.equal(CONTRACT_ADDITIONS["--space-5"], "20px");
});

test("buildTokensCss is deterministic", () => {
  assert.equal(buildTokensCss(SOURCE), buildTokensCss(SOURCE));
});

test("buildTokensCss throws when the source already declares a contract addition", () => {
  assert.throws(() => buildTokensCss(":root { --bg: #fff; --meta: red; }"), /--meta/);
});

test("checkTokens reports missing, stale and fresh tokens.css", () => {
  const missing = checkTokens(SOURCE, undefined);
  assert.equal(missing.ok, false);
  assert.match(missing.message, /npm run build:tokens/);
  const stale = checkTokens(SOURCE, "stale");
  assert.equal(stale.ok, false);
  assert.match(stale.message, /npm run build:tokens/);
  assert.equal(checkTokens(SOURCE, buildTokensCss(SOURCE)).ok, true);
});
